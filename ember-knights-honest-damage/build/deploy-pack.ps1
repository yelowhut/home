#Requires -Version 5.1
<#
.SYNOPSIS
    Assemble / refresh a BepInEx deployment for Ember Knights using a v31-capable BepInEx build.

.DESCRIPTION
    Ember Knights is Unity 2022.3.62f3 with IL2CPP metadata version 31. BepInEx 6.0.0-be.697
    bundles a Cpp2IL (2022.1.0.0) that CANNOT read metadata v31, and its BepInEx.Unity.IL2CPP
    bootstrap crashed (BadImageFormatException in Il2CppSystem.String..cctor during delegate
    bridging). BepInEx 6.0.0-be.735 bundles Cpp2IL 2022.1.0-pre-release.19 (v31-capable) and a
    revised BepInEx.Unity.IL2CPP/preloader stack.

    Il2CppInterop (Generator/Runtime/Common) is byte-identical between be.697 and be.735
    (both 1.4.6-ci.426), so the plugin's interop ABI is unchanged. Only the BepInEx.Unity.IL2CPP
    bootstrap + Cpp2IL/LibCpp2IL differ.

    This script (re)assembles a target BepInEx install:
      - Lays down the be.735 pack (core/, patchers/, dotnet/, doorstop loader)
      - Preserves UpdateInteropAssemblies=false (pre-placed interop, no runtime self-gen)
      - Copies the freshly-built plugin (HonestDamage.*.dll) into BepInEx/plugins
      - Copies the freshly-generated interop (lib/interop/*.dll) into BepInEx/interop
      - Deletes any stale BepInEx/interop/*.dll and LogOutput.log first (clean log)

.PARAMETER Target
    'dist'  -> dist/BepInEx-pack/  (the deliverable)
    'live'  -> the live Steam game install (mirrors the same fix so the user just relaunches)

.NOTES
    Prerequisites (gitignored, download via gen-interop.ps1 / manually):
      build/tools/BepInEx-be735/   (extracted BepInEx-Unity.IL2CPP-win-x64-6.0.0-be.735 zip)
      lib/interop/*.dll            (generated by gen-interop.ps1 with the be.735 toolchain)
    Plugin must be built first:
      dotnet build src/HonestDamage.Plugin -c Release -o build/work/plugin-bin
#>
param(
    [Parameter(Mandatory = $true)]
    [ValidateSet('dist', 'live')]
    [string]$Target
)

$ErrorActionPreference = "Stop"

$root      = Split-Path $PSScriptRoot -Parent
$be735     = Join-Path $root "build\tools\BepInEx-be735"
$interop   = Join-Path $root "lib\interop"
$pluginBin = Join-Path $root "build\work\plugin-bin"

$gameRoot  = "C:\Program Files (x86)\Steam\steamapps\common\EmberKnights"

if ($Target -eq 'dist') {
    $packRoot = Join-Path $root "dist\BepInEx-pack"
} else {
    $packRoot = $gameRoot
}

# --- Validate prerequisites ---
foreach ($p in @($be735, $interop, $pluginBin)) {
    if (-not (Test-Path $p)) { Write-Error "Missing prerequisite: $p" }
}
if (-not (Get-ChildItem $interop -Filter "Assembly-CSharp.dll" -ErrorAction SilentlyContinue)) {
    Write-Error "lib/interop has no Assembly-CSharp.dll - run gen-interop.ps1 first"
}

$bepinexDir = Join-Path $packRoot "BepInEx"
$configFile = Join-Path $bepinexDir "config\BepInEx.cfg"

# --- Preserve existing config (UpdateInteropAssemblies=false + our plugin settings) ---
$savedConfig = $null
if (Test-Path $configFile) {
    $savedConfig = Get-Content $configFile -Raw
    Write-Host "[*] Preserved existing BepInEx.cfg"
}

# --- Lay down be.735 pack (core/, patchers/, dotnet/, doorstop loader) ---
Write-Host "[*] Laying down be.735 pack into $packRoot ..."

# Loader files at root
foreach ($f in @("winhttp.dll", ".doorstop_version", "doorstop_config.ini", "changelog.txt")) {
    $src = Join-Path $be735 $f
    if (Test-Path $src) { Copy-Item $src (Join-Path $packRoot $f) -Force }
}
# dotnet runtime (replace wholesale to avoid leaving be.697-only files behind)
$dotnetDst = Join-Path $packRoot "dotnet"
if (Test-Path $dotnetDst) { Remove-Item $dotnetDst -Recurse -Force }
Copy-Item (Join-Path $be735 "dotnet") $packRoot -Recurse -Force
# BepInEx core + patchers (replace wholesale)
$be735Bep = Join-Path $be735 "BepInEx"
foreach ($sub in @("core", "patchers")) {
    $dst = Join-Path $bepinexDir $sub
    if (Test-Path $dst) { Remove-Item $dst -Recurse -Force }
    $src = Join-Path $be735Bep $sub
    if (Test-Path $src) { Copy-Item $src $bepinexDir -Recurse -Force }
}

# --- Restore preserved config (keeps UpdateInteropAssemblies=false), else seed from be.735 ---
New-Item -ItemType Directory -Force -Path (Join-Path $bepinexDir "config") | Out-Null
if ($savedConfig) {
    Set-Content -Path $configFile -Value $savedConfig -NoNewline
    Write-Host "[*] Restored preserved BepInEx.cfg"
} else {
    $be735Cfg = Join-Path $be735Bep "config\BepInEx.cfg"
    if (Test-Path $be735Cfg) { Copy-Item $be735Cfg $configFile -Force }
    # Force the critical setting
    if (Test-Path $configFile) {
        (Get-Content $configFile -Raw) -replace 'UpdateInteropAssemblies\s*=\s*true', 'UpdateInteropAssemblies = false' |
            Set-Content -Path $configFile -NoNewline
        Write-Host "[*] Seeded config from be.735 and set UpdateInteropAssemblies=false"
    }
}

# --- Fresh interop: delete stale, copy fresh ---
# IMPORTANT: lib/interop also contains Il2CppInterop.Runtime.dll + Il2CppInterop.Common.dll
# (kept there only so the plugin can COMPILE against them). At runtime those two live in
# BepInEx/core/ ONLY. Copying them into BepInEx/interop/ would duplicate Il2CppInterop.Runtime
# in two load paths -- the exact assembly whose DelegateSupport/Il2CppSystem.String..cctor is
# in the original crash. So exclude them; interop/ must contain ONLY game proxy assemblies.
$interopDst = Join-Path $bepinexDir "interop"
$interopExclude = @("Il2CppInterop.Runtime.dll", "Il2CppInterop.Common.dll")
New-Item -ItemType Directory -Force -Path $interopDst | Out-Null
Get-ChildItem $interopDst -Filter "*.dll" -ErrorAction SilentlyContinue | Remove-Item -Force
Get-ChildItem $interop -Filter "*.dll" | Where-Object { $interopExclude -notcontains $_.Name } |
    ForEach-Object { Copy-Item $_.FullName $interopDst -Force }
Write-Host "[*] Copied $((Get-ChildItem $interopDst -Filter '*.dll' | Measure-Object).Count) interop DLLs (excluding Il2CppInterop.Runtime/Common)"

# --- Fresh plugin ---
$pluginDst = Join-Path $bepinexDir "plugins"
New-Item -ItemType Directory -Force -Path $pluginDst | Out-Null
Copy-Item (Join-Path $pluginBin "HonestDamage.Plugin.dll") $pluginDst -Force
Copy-Item (Join-Path $pluginBin "HonestDamage.Core.dll")   $pluginDst -Force
Write-Host "[*] Copied plugin DLLs: HonestDamage.Plugin.dll, HonestDamage.Core.dll"

# --- Clean log for a fresh relaunch ---
$log = Join-Path $bepinexDir "LogOutput.log"
if (Test-Path $log) { Remove-Item $log -Force; Write-Host "[*] Deleted stale LogOutput.log" }

Write-Host ""
Write-Host "Done. Target '$Target' updated to BepInEx be.735 with fresh interop + plugin." -ForegroundColor Green
Write-Host "  BepInEx core: $((Get-ChildItem (Join-Path $bepinexDir 'core') -Filter '*.dll' | Measure-Object).Count) DLLs"
Write-Host "  interop:      $((Get-ChildItem $interopDst -Filter '*.dll' | Measure-Object).Count) DLLs"
Write-Host "  plugins:      $((Get-ChildItem $pluginDst -Filter '*.dll' | Measure-Object).Count) DLLs"
